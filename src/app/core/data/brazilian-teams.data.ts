export type BrazilianSerie = 'A' | 'B' | 'C' | 'D';

export interface BrazilianTeamOption {
  name: string;
  serie: BrazilianSerie;
  slug: string;
}

function team(name: string, serie: BrazilianSerie): BrazilianTeamOption {
  const slug = name
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
  return { name, serie, slug };
}

